OUT_ROOT = r"C:\Users\Phili\OneDrive\Documents\Projects\Gene Mutation\raw\chromosome_yolo"

TRAIN_TXT = r"C:\Users\Phili\OneDrive\Documents\Projects\Gene Mutation\raw\train.txt"
TEST_TXT = r"C:\Users\Phili\OneDrive\Documents\Projects\Gene Mutation\raw\test.txt"

VAL_FRACTION = 0.2 
RANDOM_SEED = 0

COPY_IMAGES = True

SKIP_DIFFICULT = False

CLEAN_OUTPUT = True
CLASSES = [
    "A1", "A2", "A3",                                    # group A: 1-3
    "B4", "B5",                                          # group B: 4-5
    "C6", "C7", "C8", "C9", "C10", "C11", "C12",         # group C: 6-12
    "D13", "D14", "D15",                                 # group D: 13-15
    "E16", "E17", "E18",                                 # group E: 16-18
    "F19", "F20",                                        # group F: 19-20
    "G21", "G22",                                        # group G: 21-22
    "X", "Y",                                            # sex chromosomes
]

CLASS_TO_ID = {name: i for i, name in enumerate(CLASSES)}

AUTOSOMES = [c for c in CLASSES if c not in ("X", "Y")]

def load_split_file(path):

    if not path or not os.path.isfile(path):
        return None
    stems = set()
    with open(path, "r", encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            line =  line.strip()
            if not line:
                continue
            token = line.split()[0]
            token = token.replace("\\", "/").split("/")[-1]
            stems.add(os.path.splitext(token)[0])
    return stems

def index_images(img_root):
    index = {}
    for ext in ("jpg", "jpeg", "png", "bmp", "tif", "tiff"):
        for pattern in (ext, ext.upper()):
            for path in glob.glob(os.path.join(img_root, "**",  f"*.{pattern}"),
                                  recursive=True):
                stem = os.path.splitext(os.path.basename(path))[0]
                index.setdefault(stem, path)
    return index

def convert_box(xmin, ymin, xmax, ymax, width, height):
    x_center = ((xmin + xmax) / 2.0) / width
    y_center = ((ymin + ymax) / 2.0) / height
    box_w = (xmax - xmin) / width
    box_h = (ymax - ymin) / height
    return x_center, y_center, box_w, box_h

def clamp01(value):
    return max(0.0, min(1.0, value))

def parse_annotation(xml_path):
    try:
        root = ET.parse(xml_path).getroot()
    except ET.ParseError as exc:
        print(f"  [skip] malformed XML: {xml_path} ({exc})")
        return None

    size = root.find("size")
    if size is None:
        print(f"  [skip] no <size> tag: {xml_path}")
        return None

    width = int(float(size.find("width").text))
    height = int(float(size.find("height").text))
    if width <= 0 or height <= 0:
        print(f"  [skip] bad image size {width}x{height}: {xml_path}")
        return None

    rows = []
    for obj in root.findall("object"):
        name = obj.find("name").text.strip()

        if SKIP_DIFFICULT:
            difficult = obj.find("difficult")
            if difficult is not None and difficult.text.strip() == "1":
                continue

        if name not in CLASS_TO_ID:
            print(f"  [warn] unknown class '{name}' in {xml_path}")
            continue

        box = obj.find("bndbox")
        xmin = float(box.find("xmin").text)
        ymin = float(box.find("ymin").text)
        xmax = float(box.find("xmax").text)
        ymax = float(box.find("ymax").text)

        if xmax < xmin:
            xmin, xmax = xmax, xmin
        if ymax < ymin:
            ymin, ymax = ymax, ymin

        xmin, xmax = max(0.0, xmin), min(float(width), xmax)
        ymin, ymax = max(0.0, ymin), min(float(height), ymax)
        if xmax - xmin < 1 or ymax - ymin < 1:
            print(f"  [warn] degenerate box for '{name}' in {xml_path}")
            continue

        x, y, w, h = convert_box(xmin, ymin, xmax, ymax, width, height)
        rows.append((
                CLASS_TO_ID[name],
                clamp01(x), clamp01(y), clamp01(w), clamp01(h),
            ))

    return width, height, rows

def prepare_dirs(out_root):
    if CLEAN_OUTPUT and os.path.isdir(out_root):
        shutil.rmtree(out_root)
    for split in ("train", "val"):
        os.makedirs(os.path.join(out_root, "images", split), exist_ok=True)
        os.makedirs(os.path.join(out_root, "labels", split), exist_ok=True)

def write_data_yaml(out_root):
    yaml_path = os.path.join(out_root, "data.yaml")
    with open(yaml_path, "w", encoding="utf-8") as fh:
        fh.write("# Auto-generated by voc_to_yolo.py - do not hand-edit\n")
        fh.write(f"path: {out_root}\n")
        fh.write("train: images/train\n")
        fh.write("val: images/val\n\n")
        fh.write(f"nc: {len(CLASSES)}\n")
        fh.write("names:\n")
        for i, name in enumerate(CLASSES):
            fh.write(f"  {i}: {name}\n")
    return yaml_path


def verify_labels(out_root, sample_size=50):

    problems = []
    all_labels = glob.glob(os.path.join(out_root, "labels", "**", "*.txt"),
                        recursive=True)
    if not all_labels:
        return ["no label files were written at all"]

    for path in random.sample(all_labels, min(sample_size, len(all_labels))):
        with open(path, "r", encoding="utf-8") as fh:
            for lineno, line in enumerate(fh, 1):
                parts = line.split()
                if len(parts) != 5:
                    problems.append(f"{path}:{lineno} has {len(parts)} fields")
                    continue
                cls_id = int(parts[0])
                coords = [float(p) for p in parts[1:]]
                if not 0 <= cls_id < len(CLASSES):
                    problems.append(f"{path}:{lineno} class id {cls_id}")
                if any(not 0.0 <= c <= 1.0 for c in coords):
                    problems.append(f"{path}:{lineno} coords out of range")
    return problems

def main():
    xml_files = glob.glob(os.path.join(XML_ROOT, "**", "*.xml"), recursive=True)
    print(f"XML files found: {len(xml_files)}")
    if not xml_files:
        print("Nothing to do - check XML_ROOT.")
        return

    image_index = index_images(IMG_ROOT)
    print(f"Images indexed:  {len(image_index)}")

    train_stems = load_split_file(TRAIN_TXT)
    test_stems = load_split_file(TEST_TXT)

    if train_stems and test_stems:
        overlap = train_stems & test_stems
        if overlap:
            print(f"[!] {len(overlap)} stems appear in BOTH split files - "
                f"they will be treated as train, e.g. {list(overlap)[:3]}")
        print(f"Using dataset split files: "
            f"{len(train_stems)} train / {len(test_stems)} test")
        use_official_split = True
    else:
        pct = int(VAL_FRACTION * 100)
        print(f"Split files not usable - falling back to a random "
            f"{100 - pct}/{pct} split")
        use_official_split = False

    random.seed(RANDOM_SEED)
    prepare_dirs(OUT_ROOT)

    counts = {"train": 0, "val": 0}
    class_counts = Counter()
    missing_images = []
    unsplit = []
    empty_labels = []

    for xml_path in xml_files:
        stem = os.path.splitext(os.path.basename(xml_path))[0]  

        if use_official_split:
            if stem in train_stems:
                split = "train"
            elif stem in test_stems:
                split = "val"
            else:
                unsplit.append(stem)
                continue
        else:
            split = "val" if random.random() < VAL_FRACTION else "train" 

        img_path = image_index.get(stem)
        if img_path is None:
            missing_images.append(stem)
            continue

        parsed = parse_annotation(xml_path)
        if parsed is None:
            continue
        _, _, rows = parsed

        if not rows:
            empty_labels.append(stem)

        label_path = os.path.join(OUT_ROOT, "labels", split, stem + ".txt")
        with open(label_path, "w", encoding="utf-8") as fh:
            for cls_id, x, y, w, h in rows:
                fh.write(f"{cls_id} {x:.6f} {y:.6f} {w:.6f} {h:.6f}\n")
                class_counts[CLASSES[cls_id]] += 1

        img_ext = os.path.splitext(img_path)[1]
        dest_img = os.path.join(OUT_ROOT, "images", split, stem + img_ext)
        if COPY_IMAGES:
            shutil.copy2(img_path, dest_img)
        elif not os.path.exists(dest_img):
            os.symlink(img_path, dest_img)

        counts[split] += 1

    yaml_path = write_data_yaml(OUT_ROOT)
    total_images = counts["train"] + counts["val"]

    print("\n" + "=" * 56)
    print("CONVERSION COMPLETE")
    print("=" * 56)
    print(f"train images: {counts['train']}")
    print(f"val images:   {counts['val']}")
    print(f"data.yaml:    {yaml_path}")

    if missing_images:
        print(f"\n[!] {len(missing_images)} XML files had no matching image, "
            f"e.g. {missing_images[:5]}")
    if unsplit:
        print(f"\n[!] {len(unsplit)} XML files were in neither split file, "
            f"e.g. {unsplit[:5]}")
    if empty_labels:
        print(f"\n[!] {len(empty_labels)} images produced an empty label file, "
            f"e.g. {empty_labels[:5]}") 

    print("\nObjects written per class:")
    print(f"  {'class':>5}  {'count':>7}  {'per image':>9}")
    for name in CLASSES:
        n = class_counts[name]
        ratio = n / total_images if total_images else 0
        print(f"  {name:>5}  {n:>7}  {ratio:>9.2f}")
    print(f"  {'TOTAL':>5}  {sum(class_counts.values()):>7}")

    off = [c for c in AUTOSOMES
        if total_images and abs(class_counts[c] / total_images - 2.0) > 0.05]
    if off:
        print(f"\n[!] autosomes far from 2.00 per image: {off}")
        print("    A few are expected (real aneuploidies). Many means "
            "something went wrong in parsing or matching.")

    problems = verify_labels(OUT_ROOT)
    if problems:
        print(f"\n[!] label verification found {len(problems)} problems:")
        for p in problems[:10]:
            print(f"    {p}")
    else:
        print("\nLabel spot-check passed: ids and coordinates all in range.")

    print("\nNext step:")
    print(f'  yolo detect train data="{yaml_path}" '
        f'model=yolo11s.pt epochs=100 imgsz=640')


if __name__ == "__main__":
    main()
               




